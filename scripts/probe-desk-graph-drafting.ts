import assert from "node:assert/strict";
import { CREATE_PARENT, graphDiscussionOutput, openGraphCreateRig } from "../src/conversations/domain-adapters/work-graph/fixtures/graph-create";
import { withDraftBrowserProbe } from "./desk-make-editor/server";

const rig = await openGraphCreateRig();
rig.state.output = graphDiscussionOutput();
await withDraftBrowserProbe(rig, async ({ page, calls, errors }) => {
  await page.getByRole("button", { name: "Make", exact: true }).click();
  const editor = page.getByRole("article", { name: "Draft editor", exact: true });
  const title = page.getByLabel("title (required)", { exact: true });
  const body = page.getByLabel("body", { exact: true });
  await title.waitFor();
  assert.equal(await title.inputValue(), "Investigate receipt preservation across restart");
  assert.match(await body.inputValue(), /Problem:[\s\S]*Intended result:[\s\S]*Evidence:[\s\S]*Constraints:/);
  const parent = page.getByLabel("parent (required)", { exact: true });
  const parentField = editor.locator("fieldset", { has: parent });
  await parentField.getByText("Suggested", { exact: true }).waitFor();
  assert.equal(calls.filter(call => call.includes("/details")).length, 0);
  await parentField.getByRole("button", { name: "Sources for parent", exact: true }).click();
  await parentField.getByText("turn: turn-example, revision 1").waitFor();
  assert.equal(calls.filter(call => call.includes("/details")).length, 1);
  assert.equal((await parent.inputValue()).includes("adapterId"), false);
  await page.screenshot({ path: (process.argv[2] ?? "/tmp/desk-graph-drafting.png").replace(/\.png$/, "-prefilled.png"), fullPage: true });
  console.log("Make populated title, substantive body, checkpoint and suggested canonical references; source details loaded only on demand.");

  const revision = async () => Number(await editor.getAttribute("data-revision"));
  const changed = async (before: number) => { await page.waitForFunction(value => Number(document.querySelector('[aria-label="Draft editor"]')?.getAttribute("data-revision")) > value, before); };
  await title.fill("Audit restart receipts");
  let before = await revision();
  await page.getByRole("button", { name: "Save title", exact: true }).click();
  await changed(before);
  before = await revision();
  await page.getByRole("button", { name: "Clear body", exact: true }).click();
  await changed(before);
  rig.state.head = "2";
  rig.state.output = graphDiscussionOutput(true);
  const reopening = page.waitForResponse(response => response.request().method() === "GET" && /\/api\/desk\/drafts\/[^/]+$/.test(new URL(response.url()).pathname));
  await page.getByRole("button", { name: "Reopen draft", exact: true }).click();
  await (await reopening).finished();
  await page.getByText(/Review needed: conversation-changed/).waitFor();
  before = await revision();
  await page.getByRole("button", { name: "Refresh draft", exact: true }).click();
  await changed(before);
  assert.equal(await title.inputValue(), "Audit restart receipts");
  assert.equal(await body.inputValue(), "");
  await rig.reopen();
  const generations = rig.state.requests.length;
  await page.reload();
  await page.getByRole("button", { name: "Make", exact: true }).click();
  await title.waitFor();
  assert.equal(await title.inputValue(), "Audit restart receipts");
  assert.equal(await body.inputValue(), "");
  assert.equal(rig.state.requests.length, generations);
  console.log("Edit, deliberate clear and explicit refresh preserved owned fields; Make reopened the same durable draft after host restart without generation.");

  await parent.fill(CREATE_PARENT);
  before = await revision();
  await page.getByRole("button", { name: "Save parent", exact: true }).click();
  await changed(before);
  await page.getByRole("complementary", { name: "Destination changes" }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Confirm draft" }).isDisabled(), true);
  await page.getByLabel("I reviewed the destination changes").check();
  await page.getByRole("button", { name: "Confirm draft" }).click();
  await page.getByText("Confirmation needs review: destination-changed.").waitFor();
  before = await revision();
  await page.getByRole("button", { name: "Refresh draft", exact: true }).click();
  await changed(before);
  assert.equal(await parent.inputValue(), CREATE_PARENT);
  assert.equal(await body.inputValue(), "");
  rig.state.localOnly = true;
  await page.getByRole("button", { name: "Refresh draft", exact: true }).click();
  await page.getByText("No permitted model is available; the manual draft is unchanged.").waitFor();
  await page.getByRole("button", { name: "Confirm draft" }).click();
  await page.getByText("Policy withholds draft fields in this context. Open the draft in a permitted context before confirming.").waitFor();
  assert.equal(rig.soma.calls.length, 0);
  assert.equal((await rig.authority.inspectHostRecords()).confirmations.length, 0);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: process.argv[2] ?? "/tmp/desk-graph-drafting.png", fullPage: true });
  console.log("Changed destination required explicit refresh; unavailable permitted model kept edits; confirmation was blocked. Graph mutation calls and authority confirmations: 0.");
});
