import { strict as assert } from "node:assert";
import { join } from "node:path";
import { chromium } from "playwright";
import { DEFAULT_SETTINGS, findNode } from "../src/balance";
import { initDatabase } from "../src/surface/mc/db/init";
import { saveBalanceState, loadBalanceState } from "../src/surface/mc/desk/balance-store";
import { composeDesk } from "../src/surface/mc/desk/compose";
import { HandledLedger } from "../src/surface/mc/desk/actions";
import { deskFixtureOptions } from "../src/surface/mc/__tests__/fixtures/desk-options-fixture";
import { handleDeskMyDay } from "../src/surface/mc/api/desk-my-day";
import { runWithTemporaryHome } from "./probe-temp-home";

await runWithTemporaryHome(import.meta.path, async () => {
  const db = initDatabase(":memory:");
  const options = { ...deskFixtureOptions, areas: [{ id: "work", label: "Work", color: "", repos: [], goals: [] }] };
  const runtime = { options, ledger: new HandledLedger() };
  const task = { id: "parent", title: "Prepare workshop", weight: 50, ordering: "parallel" as const, effort: 1 as const, children: [] };
  saveBalanceState(db, { outline: { id: "root", title: "Outline", weight: 100, ordering: "parallel", children: [{ id: "area:work", title: "Work", weight: 100, ordering: "parallel", children: [task] }] }, log: [], settings: { ...DEFAULT_SETTINGS }, dayState: null, history: { deficits: {}, lastSurfaced: {} } });
  const bundle = await Bun.build({ entrypoints: [join(import.meta.dir, "desk-balance-controls/browser-probe.tsx")], target: "browser", outdir: "/tmp/balance-controls-bundle" });
  assert.ok(bundle.success, "Browser bundle failed");
  const commands: string[] = [];
  const outline = () => { const state = loadBalanceState(db); assert.ok(state); return state.outline; };
  const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: async req => {
    const url = new URL(req.url);
    const asset = bundle.outputs.find(output => url.pathname === `/${output.path.split("/").at(-1)}`);
    if (asset) return new Response(asset);
    if (url.pathname === "/fixture.json") return Response.json(await composeDesk(db, options, undefined));
    if (url.pathname === "/api/desk/my-day") {
      if (req.method === "POST") commands.push((await req.clone().json() as { command: { op: string } }).command.op);
      return handleDeskMyDay(req, db, runtime);
    }
    return new Response('<!doctype html><html><head><link rel="stylesheet" href="/browser-probe.css"></head><body><div id="root"></div><script type="module" src="/browser-probe.js"></script></body></html>', { headers: { "content-type": "text/html" } });
  } });
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
    page.on("pageerror", error => { throw error; });
    await page.goto(server.url.toString());
    const plus = page.getByRole("button", { name: "Add subtask to Prepare workshop", exact: true });
    await plus.waitFor({ state: "attached" });
    assert.equal(await plus.evaluate(element => getComputedStyle(element).opacity), "0");
    await plus.focus();
    assert.equal(await plus.evaluate(element => getComputedStyle(element).opacity), "1");
    await plus.blur();
    await plus.hover();
    assert.equal(await plus.evaluate(element => getComputedStyle(element).opacity), "1");
    const buttonBox = await plus.boundingBox();
    const iconBox = await plus.locator("svg").boundingBox();
    assert.ok(buttonBox && iconBox);
    assert.equal(buttonBox.width, 24);
    assert.equal(buttonBox.height, 24);
    assert.equal(iconBox.width, 14);
    assert.equal(iconBox.height, 14);
    assert.ok(Math.abs(buttonBox.x + buttonBox.width / 2 - iconBox.x - iconBox.width / 2) < 1);
    assert.ok(Math.abs(buttonBox.y + buttonBox.height / 2 - iconBox.y - iconBox.height / 2) < 1);
    assert.equal(await plus.evaluate(element => getComputedStyle(element).borderTopWidth), "0px");
    await page.screenshot({ path: "/tmp/balance-add-icon-hover.png", fullPage: true });
    await plus.click();
    const dialog = page.getByRole("dialog", { name: "Add task", exact: true });
    await dialog.waitFor({ state: "visible" });
    assert.equal(await dialog.evaluate(element => element.matches(":modal")), true);
    assert.ok((await dialog.getByRole("combobox", { name: "New Balance parent" }).inputValue()).includes("Prepare workshop"));
    await dialog.getByRole("textbox", { name: "New Balance title" }).fill("Print handouts");
    await dialog.getByRole("slider", { name: "Balance importance" }).fill("73");
    await dialog.getByRole("spinbutton", { name: "Balance estimate minutes" }).fill("25");
    await dialog.getByRole("combobox", { name: "Balance effort credit" }).selectOption("4");
    await dialog.getByLabel("Balance due date", { exact: true }).fill("2026-12-24");
    await dialog.getByRole("textbox", { name: "Balance context" }).fill("Office");
    await dialog.getByRole("textbox", { name: "Balance notes" }).fill("Bring the signed form");
    await page.screenshot({ path: "/tmp/balance-task-modal.png", fullPage: true });
    await dialog.getByRole("button", { name: "Confirm add" }).click();
    await dialog.waitFor({ state: "detached" });
    const state = loadBalanceState(db);
    const created = state && findNode(state.outline, "parent")?.children[0];
    assert.ok(created);
    assert.deepEqual({ title: created.title, weight: created.weight, effort: created.effort, estimateMinutes: created.estimateMinutes, dueDate: created.dueDate, context: created.context, note: created.note }, { title: "Print handouts", weight: 73, effort: 4, estimateMinutes: 25, dueDate: "2026-12-24", context: "Office", note: "Bring the signed form" });
    assert.deepEqual(commands, ["outline-add"]);
    const inspector = page.getByRole("complementary", { name: "Selected Balance item" });
    await inspector.getByRole("button", { name: "+ Add subtask", exact: true }).click();
    await dialog.waitFor({ state: "visible" });
    await page.keyboard.press("Escape");
    await dialog.waitFor({ state: "detached" });
    await plus.click();
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    assert.deepEqual(commands, ["outline-add"]);
    page.once("dialog", prompt => { void prompt.dismiss(); });
    await inspector.getByRole("button", { name: "Delete task", exact: true }).click();
    assert.ok(findNode(outline(), created.id));
    page.once("dialog", prompt => { void prompt.accept(); });
    await inspector.getByRole("button", { name: "Delete task", exact: true }).click();
    await page.getByRole("button", { name: "Add subtask to Print handouts", exact: true }).waitFor({ state: "detached" });
    assert.equal(findNode(outline(), created.id), null);
    assert.deepEqual(commands, ["outline-add", "outline-remove"]);
    await page.screenshot({ path: "/tmp/balance-task-deleted.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "+ Add task", exact: true }).click();
    await dialog.waitFor({ state: "visible" });
    assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true);
    await page.screenshot({ path: "/tmp/balance-task-modal-mobile.png", fullPage: true });
    console.log("PASS: modal metadata persisted in one save; hover and focus plus select parent; Escape and Cancel do not save; delete cancel preserves and delete confirm removes; mobile dialog fits.");
  } finally { await browser.close(); server.stop(true); db.close(); }
});
