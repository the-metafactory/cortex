import type { Page } from "playwright";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { openPrototypeBrowser } from "./desk-ui-prototype-browser";
const { browser, origin, output } = await openPrototypeBrowser("/tmp/cortex-3290-conversation-evidence");
const ensure = (value: unknown, reason: string) => { if (!value) throw new Error(reason); };
const noPlumbing = async (page: Page) => {
  const visible = await page.locator("body").innerText();
  const forbidden = /\b(schema|renderer|protocol|generation|checkpoint|query)\b/i.exec(visible);
  ensure(!forbidden, `Technical plumbing visible in the conversation: ${forbidden?.[0]}`);
  for (const label of ["Adapter", "Renderer", "Simulated state", "Prototype variants", "Object views"]) ensure(await page.getByLabel(label, { exact: true }).count() === 0, `Technical control visible: ${label}`);
  ensure(await page.locator("pre,iframe,.dap-switcher").count() === 0, "The normal conversation contains a diagnostic view");
};
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const pageErrors: string[] = [];
  const requests: string[] = [];
  page.on("pageerror", error => pageErrors.push(error.message));
  page.on("request", request => { if (!request.url().startsWith(origin)) requests.push(request.url()); });
  await page.goto(`${origin}/?desk=adapter-ui-prototype`);
  await page.waitForFunction(() => document.querySelector("[data-task-prototype], [data-prototype-state]"));
  await noPlumbing(page);
  await page.getByRole("heading", { name: "Release review", exact: true }).waitFor();
  await page.screenshot({ path: join(output, "desktop-conversation.png"), fullPage: true });
  const writes = () => page.locator("[data-task-prototype]").getAttribute("data-synthetic-writes");
  ensure(await writes() === "0", "Opening a conversation created a task");
  await page.getByRole("textbox", { name: "Message Ivy", exact: true }).fill("turn this into a task");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  const card = page.getByRole("article", { name: "Proposed Balance task", exact: true });
  await card.waitFor();
  ensure(await card.getByRole("button").allTextContents().then(values => values.join("|")) === "Approve|Edit", "Proposal has more than Approve and Edit as its primary actions");
  await card.getByRole("heading", { name: "Review the release checklist", exact: true }).waitFor();
  await noPlumbing(page);
  await page.screenshot({ path: join(output, "desktop-proposal.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile conversation overflows horizontally");
  await page.screenshot({ path: join(output, "mobile-proposal.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await card.getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByRole("textbox", { name: "Title", exact: true }).fill("Discard this edit");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await card.getByRole("heading", { name: "Review the release checklist", exact: true }).waitFor();
  await card.getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByRole("textbox", { name: "Title", exact: true }).fill("");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "Give this task a title." }).waitFor();
  ensure(await writes() === "0", "Validation created a task");
  await page.getByRole("textbox", { name: "Title", exact: true }).fill("Audit the release checklist");
  await page.getByRole("textbox", { name: "Note", exact: true }).fill("Review rollback and alerts. Agree the final release checks.");
  await page.getByRole("button", { name: "Conversations", exact: false }).click();
  await page.getByRole("button", { name: "Release review Continue conversation →", exact: true }).click();
  ensure(await page.getByRole("textbox", { name: "Title", exact: true }).inputValue() === "Audit the release checklist", "Revisiting discarded an unsaved edit");
  await page.screenshot({ path: join(output, "desktop-edit.png"), fullPage: true });
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await card.getByRole("heading", { name: "Audit the release checklist", exact: true }).waitFor();
  ensure(await writes() === "0", "Saving edits created a task");
  await page.getByRole("textbox", { name: "Message Ivy", exact: true }).fill("turn this into a task");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  ensure(await page.getByRole("article", { name: "Proposed Balance task", exact: true }).count() === 1, "Repeated request duplicated the proposal");
  const approve = card.getByRole("button", { name: "Approve", exact: true });
  await approve.evaluate(element => { (element as HTMLButtonElement).click(); (element as HTMLButtonElement).click(); });
  await page.getByRole("article", { name: "Saved Balance task", exact: true }).waitFor();
  ensure(await writes() === "1", "Approval did not create exactly once");
  await page.getByRole("heading", { name: "Audit the release checklist", exact: true }).waitFor();
  await page.getByRole("status").filter({ hasText: "Added to Balance" }).waitFor();
  await noPlumbing(page);
  await page.screenshot({ path: join(output, "desktop-saved.png"), fullPage: true });
  await page.getByRole("button", { name: "View task →", exact: true }).click();
  await page.getByRole("button", { name: "Back to conversation", exact: false }).click();
  await page.getByRole("textbox", { name: "Message Ivy", exact: true }).fill("turn this into a task");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  ensure(await writes() === "1", "Revisiting or repeating an approved request created again");
  ensure(await page.locator("[data-task-prototype]").getAttribute("data-external-writes") === "0", "External effect counter changed");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(output, "mobile-saved.png"), fullPage: true });
  await page.goto(`${origin}/?desk=adapter-ui-prototype&variant=B`);
  await page.getByRole("heading", { name: "Release review", exact: true }).waitFor();
  await noPlumbing(page);
  ensure(requests.length === 0, "The normal prototype contacted another origin");
  ensure(pageErrors.length === 0, `Browser errors: ${pageErrors.join(";")}`);
  await writeFile(join(output, "probe.json"), JSON.stringify({ passed: true, browserVersion: browser.version(), cases: ["conversation-first default and B URL", "typed request produces one Balance card", "only Approve and Edit proposal actions", "no visible technical plumbing", "edit cancel and title validation", "unsaved edits survive conversation navigation", "save changes updates the proposal without creation", "one exact edited approval despite double click", "saved task and repeated request do not create again", "desktop/mobile without overflow", "zero external requests or effects"], syntheticOwnerWrites: 1, externalOwnerWrites: 0, requests, pageErrors, limitation: "Synthetic conversation, model and owner in memory; no real Balance task is created. Reload starts a fresh example." }, null, 2));
  console.log(`Conversation prototype browser probe passed; evidence: ${output}`);
} finally { await browser.close(); }
