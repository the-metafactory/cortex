import assert from "node:assert/strict";
import { BALANCE_DRAFT_DISCUSSION, DRAFT_GLIDER_PROJECT, DRAFT_LAB_AREA, balanceDiscussionOutput, conflictingDueOutput, openBalanceDraftRig } from "../src/conversations/domain-adapters/balance/fixtures/balance-draft";
import { withDraftBrowserProbe } from "./desk-make-editor/server";
import { denyRelease, openMakeEditor, reopenOutdatedDraft, restartAndRemake, revisionSteps } from "./desk-make-editor/steps";
import type { DraftEditorView } from "../src/surface/mc/desk/draft-editor-contract";

const rig = await openBalanceDraftRig({ discussion: BALANCE_DRAFT_DISCUSSION });
rig.state.output = balanceDiscussionOutput();
const outlineBefore = rig.outlineSnapshot();
await withDraftBrowserProbe(rig, async ({ page, calls, errors }) => {
  const { making, editor } = await openMakeEditor(page, "Balance task", BALANCE_DRAFT_DISCUSSION);
  const title = page.getByLabel("title (required)", { exact: true });
  const note = page.getByLabel("note", { exact: true });
  const due = page.getByLabel("due", { exact: true });
  const area = page.getByLabel("area (required)", { exact: true });
  const project = page.getByLabel("project", { exact: true });
  await title.waitFor();
  const made = await (await making).json() as DraftEditorView;
  assert.equal(made.view.draft.entryId, rig.makeInput.entryId);
  assert.equal(await title.inputValue(), "Cut the glider wing before the workshop");
  assert.match(await note.inputValue(), /What:[\s\S]*Why:[\s\S]*Constraints:/);
  assert.equal(await due.inputValue(), "2026-11-13");
  assert.equal(await area.inputValue(), DRAFT_LAB_AREA);
  assert.equal(await project.inputValue(), DRAFT_GLIDER_PROJECT);
  assert.equal((await area.inputValue()).includes("adapterId"), false);
  const projectField = editor.locator("fieldset", { has: project });
  await projectField.getByText("Suggested", { exact: true }).waitFor();
  assert.equal(calls.filter(call => call.includes("/details")).length, 0);
  await projectField.getByRole("button", { name: "Sources for project", exact: true }).click();
  await projectField.getByText("turn: turn-example, revision 1").waitFor();
  assert.equal(calls.filter(call => call.includes("/details")).length, 1);
  await page.screenshot({ path: (process.argv[2] ?? "/tmp/desk-balance-drafting.png").replace(/\.png$/, "-prefilled.png"), fullPage: true });
  console.log("Make populated title, note, due, area and project from the displayed discussion, with suggested markers and on-demand source details.");

  const steps = revisionSteps(page, editor);
  await title.fill("Audit the wing cut");
  await steps.press("Save title");
  await steps.press("Clear note");
  rig.state.head = "2";
  rig.state.output = balanceDiscussionOutput(true);
  await reopenOutdatedDraft(page);
  await steps.press("Refresh draft");
  assert.equal(await title.inputValue(), "Audit the wing cut");
  assert.equal(await note.inputValue(), "");
  const generations = rig.state.requests.length;
  const reopened = await restartAndRemake(page, rig, title);
  assert.equal(reopened.view.draft.draftId, made.view.draft.draftId);
  assert.equal(await title.inputValue(), "Audit the wing cut");
  assert.equal(await note.inputValue(), "");
  assert.equal(rig.state.requests.length, generations);
  console.log("Edited title and the deliberately cleared note survived explicit refresh and a host restart; Make reopened the same draft without generation.");

  rig.state.output = conflictingDueOutput();
  await steps.press("Refresh draft");
  const dueField = editor.locator("fieldset", { has: due });
  assert.equal(await due.inputValue(), "");
  await dueField.getByText("conflict", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Confirm draft" }).isDisabled(), true);
  await dueField.getByRole("button", { name: "Sources for due", exact: true }).click();
  await page.getByRole("button", { name: "Use 2026-11-13", exact: true }).waitFor();
  await steps.press("Use 2026-11-20");
  assert.equal(await due.inputValue(), "2026-11-20");
  await steps.press("Clear due");
  assert.equal(await due.inputValue(), "");
  console.log("A conflicting due date offered both alternatives with sources; the conflict blocked confirmation until the principal chose one, then omitted the date.");

  await denyRelease(page, rig);
  assert.equal(rig.ownerCalls.length, 0);
  assert.equal((await rig.authority.inspectHostRecords()).confirmations.length, 0);
  assert.equal(rig.outlineSnapshot(), outlineBefore);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: process.argv[2] ?? "/tmp/desk-balance-drafting.png", fullPage: true });
  console.log("Denied release kept manual editing and blocked confirmation. Balance owner calls, authority confirmations and outline changes: 0.");
}, { conversations: () => ({ state: "ready", host: rig.host, tookOver: null, resumed: [], reconciled: [] }), principal: rig.principal.principal, route: `/?desk=conversation&conversation=${rig.makeInput.conversationId}` });
